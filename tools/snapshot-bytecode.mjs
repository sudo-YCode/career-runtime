// Compiles one real function from each service and records what its runtime actually executes:
// javap for Java and Kotlin, V8 Ignition bytecode for Node.js, dis for CPython.
// Output: web/src/data/bytecode.generated.json, which the site shows next to the source.
// A missing toolchain is recorded as such; the site never shows made-up bytecode.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'web', 'src', 'data', 'bytecode.generated.json');
const isWin = process.platform === 'win32';

const SAMPLES = [
  { svc: 'fleet-tracker', lang: 'java', symbol: 'etaMinutes', cls: 'dev.yatin.fleet.EtaCalculator',
    file: 'runtime-samples/fleet-tracker/EtaCalculator.java', kind: 'javac' },
  { svc: 'edge-gateway', lang: 'java', symbol: 'tryAcquire', cls: 'dev.yatin.gateway.TokenBucket',
    file: 'runtime-samples/edge-gateway/TokenBucket.java', kind: 'javac' },
  { svc: 'migrator', lang: 'kotlin', symbol: 'migrate', cls: 'dev.yatin.migrator.MigrateKt',
    file: 'runtime-samples/migrator/Migrate.kt', kind: 'kotlinc' },
  { svc: 'notify', lang: 'ts', symbol: 'pickChannel', file: 'runtime-samples/notify/channel.ts', kind: 'v8' },
  { svc: 'speech', lang: 'python', symbol: 'wer', file: 'runtime-samples/speech/metrics.py', kind: 'cpython' },
];

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', shell: isWin && /\.(bat|cmd)$/i.test(cmd), ...opts });
  if (r.error) return { ok: false, out: '', err: r.error.message };
  return { ok: r.status === 0, out: r.stdout ?? '', err: r.stderr ?? '' };
}

function has(cmd, args) {
  const r = run(cmd, args);
  return r.ok ? (r.out + r.err).trim().split('\n')[0] : null;
}

/** One method's block from `javap -c -p` output. */
function javapMethod(text, symbol) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => l.includes(` ${symbol}(`));
  if (start < 0) return null;
  const block = [];
  for (let i = start; i < lines.length && lines[i].trim() !== '' && lines[i].trim() !== '}'; i++) block.push(lines[i].replace(/^ {2}/, ''));
  return block.join('\n');
}

function javaSnapshot(s, javac) {
  const tmp = mkdtempSync(join(tmpdir(), 'bc-'));
  try {
    const c = run('javac', ['-d', tmp, join(root, s.file)]);
    if (!c.ok) return { error: c.err.trim() };
    const p = run('javap', ['-c', '-p', '-cp', tmp, s.cls]);
    return { tool: 'javap -c', version: javac, bytecode: javapMethod(p.out, s.symbol) };
  } finally { rmSync(tmp, { recursive: true, force: true }); }
}

function kotlinSnapshot(s, kotlinc) {
  const tmp = mkdtempSync(join(tmpdir(), 'bc-'));
  try {
    const c = run(isWin ? 'kotlinc.bat' : 'kotlinc', [join(root, s.file), '-d', tmp]);
    if (!c.ok) return { error: c.err.trim() };
    const main = javapMethod(run('javap', ['-c', '-p', '-cp', tmp, s.cls]).out, s.symbol) ?? '';
    const cont = run('javap', ['-p', '-cp', tmp, `${s.cls}$${s.symbol}$1`]).out.trim();
    const head = main.split('\n').slice(0, 48).join('\n');
    return {
      tool: 'kotlinc + javap -c', version: kotlinc,
      bytecode: `${head}\n    …\n\n// The continuation object kotlinc generated for the suspend function:\n${cont}`,
    };
  } finally { rmSync(tmp, { recursive: true, force: true }); }
}

function v8Snapshot(s) {
  const tmp = mkdtempSync(join(tmpdir(), 'bc-'));
  try {
    const harness = join(tmp, 'harness.mjs');
    writeFileSync(harness, [
      `import { ${s.symbol} } from ${JSON.stringify(pathToFileURL(join(root, s.file)).href)};`,
      `${s.symbol}({ pushEnabled: true, quietHoursUtc: [1, 2], preferred: 'sms' }, { topic: 'career.events', priority: 'normal', ts: Date.now() });`,
    ].join('\n'));
    const r = run(process.execPath, ['--print-bytecode', `--print-bytecode-filter=${s.symbol}`, harness]);
    const lines = r.out.split(/\r?\n/);
    const start = lines.findIndex((l) => l.startsWith('[generated bytecode for function: ' + s.symbol));
    if (start < 0) return { error: (r.err || 'no bytecode printed').trim() };
    const kept = [];
    for (let i = start + 1; i < lines.length; i++) {
      const l = lines[i];
      if (l.startsWith('Constant pool') || l.startsWith('[generated')) break;
      const m = l.match(/@\s*(\d+)\s*:\s*(?:[0-9a-f]{2}\s)+\s*(.+)$/i);
      if (m) kept.push(`${m[1].padStart(4)}  ${m[2].trim().replace(/\([0-9a-f]+ @ (\d+)\)/i, '→ $1')}`);
      else if (/^(Parameter count|Register count|Frame size|Bytecode length)/.test(l)) kept.push(l.trim());
    }
    return { tool: 'node --print-bytecode (V8 Ignition, types stripped)', version: `Node ${process.version}`, bytecode: kept.join('\n') };
  } finally { rmSync(tmp, { recursive: true, force: true }); }
}

function pythonSnapshot(s, python) {
  const code = [
    'import dis, sys, importlib.util',
    'spec = importlib.util.spec_from_file_location("m", sys.argv[1])',
    'm = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)',
    `dis.dis(m.${s.symbol})`,
  ].join('\n');
  const r = run('python', ['-c', code, join(root, s.file)]);
  if (!r.ok) return { error: r.err.trim() };
  return { tool: 'python -m dis', version: python, bytecode: r.out.replace(/\s+$/, '') };
}

const javac = has('javac', ['-version']);
const kotlinc = has(isWin ? 'kotlinc.bat' : 'kotlinc', ['-version']);
const python = has('python', ['--version']);

const result = {};
for (const s of SAMPLES) {
  const source = readFileSync(join(root, s.file), 'utf8').replace(/\r\n/g, '\n');
  let snap;
  if (s.kind === 'javac') snap = javac ? javaSnapshot(s, javac) : { error: 'javac not found: install JDK 21 and re-run npm run bytecode' };
  else if (s.kind === 'kotlinc') snap = kotlinc && javac ? kotlinSnapshot(s, kotlinc) : { error: 'kotlinc not found: install the Kotlin compiler and re-run npm run bytecode' };
  else if (s.kind === 'v8') snap = v8Snapshot(s);
  else snap = python ? pythonSnapshot(s, python) : { error: 'python not found' };
  result[s.svc] = {
    file: s.file, lang: s.lang, symbol: s.symbol, source,
    tool: snap.tool ?? null, version: snap.version ?? null,
    bytecode: snap.bytecode ?? null, pending: snap.error ?? null,
    generatedAt: new Date().toISOString(),
  };
  console.log(`${s.svc.padEnd(14)} ${snap.bytecode ? 'ok' : 'pending: ' + snap.error}`);
}

writeFileSync(outFile, JSON.stringify(result, null, 2) + '\n');
console.log(`wrote ${outFile}`);
