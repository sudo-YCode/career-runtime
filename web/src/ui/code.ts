import { h } from '../util/dom';
import snapshots from '../data/bytecode.generated.json';

interface Snapshot {
  file: string; lang: 'java' | 'kotlin' | 'ts' | 'python'; symbol: string; source: string;
  tool: string | null; version: string | null; bytecode: string | null; pending: string | null; generatedAt: string;
}

const KEYWORDS: Record<Snapshot['lang'], string[]> = {
  java: ['package', 'public', 'private', 'final', 'static', 'class', 'return', 'if', 'double', 'int', 'long', 'boolean', 'synchronized', 'new', 'this', 'true', 'false'],
  kotlin: ['package', 'const', 'val', 'var', 'fun', 'suspend', 'data', 'class', 'sealed', 'interface', 'return', 'if', 'for', 'in', 'repeat'],
  ts: ['export', 'type', 'interface', 'function', 'return', 'if', 'const', 'let', 'new'],
  python: ['def', 'return', 'for', 'in', 'if', 'max', 'min', 'list', 'range', 'len', 'enumerate'],
};

/** Tiny tokenizer: comments, strings, numbers, keywords. Builds spans, never parses HTML. */
function highlight(code: string, lang: Snapshot['lang']): HTMLElement {
  const pre = h('pre', { class: 'code' });
  const kw = KEYWORDS[lang].join('|');
  const re = new RegExp(
    `(\\/\\/[^\\n]*|#[^\\n]*|\\/\\*[\\s\\S]*?\\*\\/|"""[\\s\\S]*?"""|"(?:\\\\.|[^"\\\\])*"|'(?:\\\\.|[^'\\\\])*')|\\b(\\d[\\d_.]*)\\b|\\b(${kw})\\b`,
    'g',
  );
  let last = 0;
  for (const m of code.matchAll(re)) {
    const i = m.index ?? 0;
    if (i > last) pre.append(code.slice(last, i));
    const cls = m[1] ? (/^(\/\/|#|\/\*)/.test(m[1]) ? 'c-com' : 'c-str') : m[2] ? 'c-num' : 'c-kw';
    pre.append(h('span', { class: cls }, [m[0]]));
    last = i + m[0].length;
  }
  pre.append(code.slice(last));
  return pre;
}

const LANG_LABEL: Record<Snapshot['lang'], string> = { java: 'Java', kotlin: 'Kotlin', ts: 'TypeScript', python: 'Python' };

export function codeCard(svcId: string): HTMLElement | null {
  const snap = (snapshots as Record<string, Snapshot>)[svcId];
  if (!snap) return null;
  const fileName = snap.file.split('/').pop() ?? snap.file;
  const bytecode = snap.bytecode
    ? h('pre', { class: 'code bytecode' }, [snap.bytecode])
    : h('div', { class: 'pending' }, [
        h('strong', {}, ['Bytecode snapshot pending']),
        h('span', {}, [`Generated by tools/snapshot-bytecode.mjs from this exact file. ${snap.pending ?? ''}`]),
      ]);
  return h('section', { class: 'panel code-card', 'aria-label': `Source and bytecode of ${snap.symbol}` }, [
    h('div', { class: 'code-cols' }, [
      h('div', { class: 'code-col' }, [
        h('div', { class: 'code-head' }, [h('span', { class: 'tag' }, [LANG_LABEL[snap.lang]]), h('span', {}, [fileName])]),
        highlight(snap.source, snap.lang),
      ]),
      h('div', { class: 'code-col' }, [
        h('div', { class: 'code-head' }, [
          h('span', { class: 'tag tag-dim' }, ['Bytecode']),
          h('span', {}, [snap.bytecode ? `${snap.symbol} · ${snap.tool}` : snap.symbol]),
        ]),
        bytecode,
      ]),
    ]),
    snap.version ? h('p', { class: 'code-foot' }, [`Real output of ${snap.version}, captured ${snap.generatedAt.slice(0, 10)}.`]) : null,
  ]);
}
